    static void Main()
    {
        Console.CursorVisible = false;
        McSM.Json.Data = McSM.Json.Load();

        SetConsoleOutputCP(65001);
        SetConsoleCP(65001);
        Console.OutputEncoding = System.Text.Encoding.UTF8;
        Console.InputEncoding = System.Text.Encoding.UTF8;
        McSM.Translation.Load(McSM.Json.Data.user.lang);
        int alteBreite = Console.WindowWidth;
        int alteHoehe = Console.WindowHeight;

        while (true)
        {
            int breite = Console.WindowWidth;
            int hoehe = Console.WindowHeight;

            if (breite != alteBreite || hoehe != alteHoehe)
            {
                alteBreite = breite;
                alteHoehe = hoehe;
                McSM.Json.Data.System.needsRedraw = true;
            }

            if (McSM.Json.Data.System.needsRedraw)
            {
                Console.Clear();
                if (McSM.Json.Data.gui.page == McSM.Json.Data.gui.page_alt) McSM.Lib.buttons.Clear(); else McSM.Lib.ClearButtons(); McSM.Json.Data.gui.page_alt = McSM.Json.Data.gui.page;
                Translation.Load(McSM.Json.Data.user.lang);
                Draw(breite, hoehe);
                McSM.Lib.DrawAllButtons();
                McSM.Json.Data.System.needsRedraw = false;
            }

            if (Console.KeyAvailable)
            {
                ConsoleKeyInfo key = Console.ReadKey(true);
                McSM.Lib.HandleButtonInput(key);
                McSM.Json.Data.System.needsRedraw = true;
            }

            Thread.Sleep(50);
        }
    }

    static void Draw(int breite, int hoehe)
    {
        if (McSM.Json.Data.gui.page <= -1)
        {
            Environment.Exit(0);
        }
        else if (McSM.Json.Data.gui.page == 0)
        {
            if (breite < 56 || hoehe < 25)
            {
                McSM.Lib.ZeichneRahmen(breite, hoehe, "2", ConsoleColor.Red);
                McSM.Lib.Text(0, 0, ["Your terminal window is too small. Please enlarge it to continue.", "", "Tip: you can also zoom the window so you don't have to change the size [CTRL + mouse wheel ]"], ConsoleColor.Red);


                return;
            }
            McSM.Json.Save(McSM.Json.Data);
            McSM.Lib.ZeichneRahmen(breite, hoehe, "3", ConsoleColor.DarkGray);
            McSM.Stuff.Logo();

            
            McSM.Lib.Text(0, 0, ["┌─────────────────────────────┐", "│                             │", "│   ↑ ↓ ← →  /  TAB to Move   │","│                             │","│      [ENTER] to Select      │", "│                             │", "└─────────────────────────────┘"],ConsoleColor.Blue);
            McSM.Lib.AddButton(0, hoehe*2/3, "gui.browser.app", () => WebServer.Server.Main(), "C", ConsoleColor.Green);

            McSM.Lib.AddButton(0, hoehe - 3, "gui.language", () => McSM.Json.Data.user.lang = McSM.Json.Data.user.lang == "de_de" ? "en_gb" : "de_de");

            McSM.Lib.AddButton(breite - 3, hoehe - 3, "gui.done", () => McSM.Json.Data.gui.page++, "r", ConsoleColor.Green);
            McSM.Lib.AddButton(2, hoehe - 3, "gui.exit", () => McSM.Json.Data.gui.page--, "l", ConsoleColor.Red);
        }
        else if (McSM.Json.Data.gui.page == 1)
        {
            McSM.Json.Save(McSM.Json.Data);
            McSM.Lib.AddButton(2, hoehe - 3, "gui.back", () => McSM.Json.Data.gui.page--, "l", ConsoleColor.Red);
        }
        else if (McSM.Json.Data.gui.page == 2)
        {
            McSM.Json.Save(McSM.Json.Data);
            
            McSM.Lib.ZeichneRahmen(breite, hoehe, "3", ConsoleColor.Red);
            McSM.Lib.Text(0, 0, "gui.text.disclaimer", ConsoleColor.Red);
            McSM.Lib.AddButton(breite - 3, hoehe - 3, "gui.text.disclaimer.accept", () => McSM.Json.Data.gui.page++, "r", ConsoleColor.Green);
            McSM.Stuff.Logo();
            McSM.Lib.Cut("H", 9,"6",ConsoleColor.Red);
            McSM.Lib.Cut("V", 0, "6", ConsoleColor.Red);
        }
    }
